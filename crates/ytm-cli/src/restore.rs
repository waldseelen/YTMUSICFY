use std::collections::HashMap;
use std::io::Write;

use anyhow::{Context, Result, bail};
use ytm_core::{InnerTubeClientTrait, PlaylistFetchResult, PlaylistPrivacy, Track};
use ytm_enrich::{MetadataProvider, plan_genre_split};
use ytm_ops::{compute_restore_moves, plan_restore_diff};
use ytm_store::{EnrichmentCacheStore, SnapshotStore};

use crate::cli::SplitGenreArgs;
use crate::render::{
    render_fetch_manifest_summary, render_genre_split_plan, render_mutation_batch_report,
};
use crate::runner::{
    RuntimeContext, ensure_manifest_safe_for_execute, load_playlist_by_id,
    load_playlist_with_manifest,
};

pub async fn handle_split_genre<C, S, P, V, W>(
    ctx: &mut RuntimeContext<'_, C, S, P, V, W>,
    args: &SplitGenreArgs,
) -> Result<()>
where
    C: InnerTubeClientTrait,
    S: SnapshotStore + EnrichmentCacheStore,
    P: MetadataProvider,
    W: Write,
{
    let fetched = load_playlist_with_manifest(ctx.client, &args.playlist).await?;
    let playlist = fetched.playlist;
    writeln!(
        ctx.out,
        "{}",
        render_fetch_manifest_summary(&fetched.manifest)
    )?;

    let existing_summaries = ctx.client.get_library_playlists().await?;
    let prefix = format!("{} - ", playlist.title);

    let mut existing_playlists: HashMap<String, PlaylistFetchResult> = HashMap::new();
    let mut existing_tracks: HashMap<String, Vec<Track>> = HashMap::new();
    for summary in &existing_summaries {
        if summary.owned
            && summary
                .title
                .to_ascii_lowercase()
                .starts_with(&prefix.to_ascii_lowercase())
        {
            let hydrated = load_playlist_with_manifest(ctx.client, &summary.id).await?;
            existing_tracks.insert(summary.id.clone(), hydrated.playlist.tracks.clone());
            existing_playlists.insert(summary.id.clone(), hydrated);
        }
    }

    let plan = plan_genre_split(
        &playlist,
        &existing_summaries,
        &existing_tracks,
        ctx.enricher,
        args.min_tracks,
    )
    .await?;
    writeln!(ctx.out, "{}", render_genre_split_plan(&plan, args.execute))?;

    if !args.execute {
        return Ok(());
    }
    ensure_manifest_safe_for_execute(&fetched.manifest, args.force_incomplete, "split-genre")?;

    let mut did_snapshot_source = false;
    for bucket in &plan.buckets {
        if bucket.tracks_to_add.is_empty() {
            continue;
        }
        if !did_snapshot_source {
            ctx.store
                .save_snapshot(&playlist, "pre-split-genre")
                .await?;
            did_snapshot_source = true;
        }
        let ids: Vec<String> = bucket
            .tracks_to_add
            .iter()
            .map(|t| t.video_id.clone())
            .collect();
        if let Some(target_id) = &bucket.existing_playlist_id {
            if let Some(target_fetched) = existing_playlists.get(target_id) {
                ensure_manifest_safe_for_execute(
                    &target_fetched.manifest,
                    args.force_incomplete,
                    "split-genre (target)",
                )?;
                ctx.store
                    .save_snapshot(&target_fetched.playlist, "pre-split-genre-target")
                    .await?;
            }
            let report = ctx
                .client
                .add_playlist_items_report(target_id, &ids, false)
                .await?;
            writeln!(
                ctx.out,
                "{}",
                render_mutation_batch_report("split-genre-add", &report)
            )?;
            if !report.is_complete_success() {
                bail!(
                    "split-genre add incomplete: {}",
                    report.first_error().unwrap_or("unknown chunk error")
                );
            }
        } else {
            ctx.client
                .create_playlist(
                    &bucket.target_playlist_title,
                    "Generated by ytm split-genre",
                    PlaylistPrivacy::Private,
                    &ids,
                )
                .await?;
        }
    }

    Ok(())
}

pub async fn handle_snapshot_restore<C, S, P, V, W>(
    ctx: &mut RuntimeContext<'_, C, S, P, V, W>,
    snapshot_id: &str,
    execute: bool,
) -> Result<()>
where
    C: InnerTubeClientTrait,
    S: SnapshotStore + EnrichmentCacheStore,
    W: Write,
{
    let snap = ctx
        .store
        .load_snapshot(snapshot_id)
        .await
        .with_context(|| format!("loading snapshot {snapshot_id}"))?;
    let live = load_playlist_by_id(ctx.client, &snap.playlist.id).await?;
    let diff = plan_restore_diff(&live, &snap.playlist);

    let mode = if execute { "EXECUTE" } else { "DRY-RUN" };
    writeln!(
        ctx.out,
        "[{mode}] Restore snapshot '{}' -> playlist '{}' ({}): remove={}, add={}, target_tracks={}",
        snap.metadata.id,
        snap.playlist.title,
        snap.playlist.id,
        diff.to_remove.len(),
        diff.to_add.len(),
        snap.playlist.tracks.len()
    )?;

    if !execute {
        return Ok(());
    }

    ctx.store
        .save_snapshot(&live, &format!("pre-restore:{}", snap.metadata.id))
        .await?;

    if !diff.to_remove.is_empty() {
        ctx.client
            .remove_playlist_items(&live.id, &diff.to_remove)
            .await?;
    }
    if !diff.to_add.is_empty() {
        ctx.client
            .add_playlist_items(&live.id, &diff.to_add, diff.allow_duplicates)
            .await?;
    }

    let updated = load_playlist_by_id(ctx.client, &live.id).await?;
    let moves = compute_restore_moves(&updated, &snap.playlist);
    if !moves.is_empty() {
        ctx.client.move_playlist_items(&live.id, &moves).await?;
    }

    writeln!(
        ctx.out,
        "Snapshot restore complete for '{}'.",
        snap.playlist.title
    )?;
    Ok(())
}
