use std::collections::{HashMap, VecDeque};
use std::io::Write;

use anyhow::{Context, Result};
use ytm_core::{InnerTubeClientTrait, Playlist, PlaylistPrivacy, Track};
use ytm_enrich::{MetadataProvider, plan_genre_split};
use ytm_ops::compute_minimal_moves;
use ytm_store::{EnrichmentCacheStore, SnapshotStore};

use crate::cli::SplitGenreArgs;
use crate::render::render_genre_split_plan;
use crate::runner::{RuntimeContext, load_playlist_by_id};

pub async fn handle_split_genre<C, S, P, V, W>(
    ctx: &mut RuntimeContext<'_, C, S, P, V, W>,
    args: &SplitGenreArgs,
) -> Result<()>
where
    C: InnerTubeClientTrait,
    S: SnapshotStore + EnrichmentCacheStore,
    P: MetadataProvider,
    W: Write,
{
    let playlist = load_playlist_by_id(ctx.client, &args.playlist).await?;
    let existing_summaries = ctx.client.get_library_playlists().await?;
    let prefix = format!("{} - ", playlist.title);

    let mut existing_playlists: HashMap<String, Playlist> = HashMap::new();
    let mut existing_tracks: HashMap<String, Vec<Track>> = HashMap::new();
    for summary in &existing_summaries {
        if summary.owned
            && summary
                .title
                .to_ascii_lowercase()
                .starts_with(&prefix.to_ascii_lowercase())
        {
            let hydrated = load_playlist_by_id(ctx.client, &summary.id).await?;
            existing_tracks.insert(summary.id.clone(), hydrated.tracks.clone());
            existing_playlists.insert(summary.id.clone(), hydrated);
        }
    }

    let plan = plan_genre_split(
        &playlist,
        &existing_summaries,
        &existing_tracks,
        ctx.enricher,
        args.min_tracks,
    )
    .await?;
    writeln!(ctx.out, "{}", render_genre_split_plan(&plan, args.execute))?;

    if !args.execute {
        return Ok(());
    }

    let mut did_snapshot_source = false;
    for bucket in &plan.buckets {
        if bucket.tracks_to_add.is_empty() {
            continue;
        }
        if !did_snapshot_source {
            ctx.store
                .save_snapshot(&playlist, "pre-split-genre")
                .await?;
            did_snapshot_source = true;
        }
        let ids: Vec<String> = bucket
            .tracks_to_add
            .iter()
            .map(|t| t.video_id.clone())
            .collect();
        if let Some(target_id) = &bucket.existing_playlist_id {
            if let Some(target_pl) = existing_playlists.get(target_id) {
                ctx.store
                    .save_snapshot(target_pl, "pre-split-genre-target")
                    .await?;
            }
            ctx.client
                .add_playlist_items(target_id, &ids, false)
                .await?;
        } else {
            ctx.client
                .create_playlist(
                    &bucket.target_playlist_title,
                    "Generated by ytm split-genre",
                    PlaylistPrivacy::Private,
                    &ids,
                )
                .await?;
        }
    }

    Ok(())
}

pub async fn handle_snapshot_restore<C, S, P, V, W>(
    ctx: &mut RuntimeContext<'_, C, S, P, V, W>,
    snapshot_id: &str,
    execute: bool,
) -> Result<()>
where
    C: InnerTubeClientTrait,
    S: SnapshotStore + EnrichmentCacheStore,
    W: Write,
{
    let snap = ctx
        .store
        .load_snapshot(snapshot_id)
        .await
        .with_context(|| format!("loading snapshot {snapshot_id}"))?;
    let live = load_playlist_by_id(ctx.client, &snap.playlist.id).await?;

    let mut desired_counts: HashMap<&str, usize> = HashMap::new();
    for t in &snap.playlist.tracks {
        if !t.video_id.is_empty() {
            *desired_counts.entry(t.video_id.as_str()).or_insert(0) += 1;
        }
    }

    let mut kept_counts: HashMap<String, usize> = HashMap::new();
    let mut to_remove: Vec<(String, String)> = Vec::new();
    for t in &live.tracks {
        let want = desired_counts
            .get(t.video_id.as_str())
            .copied()
            .unwrap_or(0);
        let seen = kept_counts.entry(t.video_id.clone()).or_insert(0);
        if *seen < want {
            *seen += 1;
        } else if let Some(sid) = &t.set_video_id {
            to_remove.push((t.video_id.clone(), sid.clone()));
        }
    }

    let mut remaining_kept = kept_counts;
    let mut to_add: Vec<String> = Vec::new();
    for t in &snap.playlist.tracks {
        if t.video_id.is_empty() {
            continue;
        }
        let rem = remaining_kept.get_mut(&t.video_id).map(|c| {
            if *c > 0 {
                *c -= 1;
                true
            } else {
                false
            }
        });
        if rem != Some(true) {
            to_add.push(t.video_id.clone());
        }
    }

    let mode = if execute { "EXECUTE" } else { "DRY-RUN" };
    writeln!(
        ctx.out,
        "[{mode}] Restore snapshot '{}' -> playlist '{}' ({}): remove={}, add={}, target_tracks={}",
        snap.metadata.id,
        snap.playlist.title,
        snap.playlist.id,
        to_remove.len(),
        to_add.len(),
        snap.playlist.tracks.len()
    )?;

    if !execute {
        return Ok(());
    }

    ctx.store
        .save_snapshot(&live, &format!("pre-restore:{}", snap.metadata.id))
        .await?;

    if !to_remove.is_empty() {
        ctx.client
            .remove_playlist_items(&live.id, &to_remove)
            .await?;
    }
    if !to_add.is_empty() {
        let allow_dupes = desired_counts.values().any(|&cnt| cnt > 1);
        ctx.client
            .add_playlist_items(&live.id, &to_add, allow_dupes)
            .await?;
    }

    let updated = load_playlist_by_id(ctx.client, &live.id).await?;
    let mut set_queues: HashMap<&str, VecDeque<String>> = HashMap::new();
    let mut current_set_ids = Vec::new();
    for t in &updated.tracks {
        if let Some(sid) = &t.set_video_id {
            current_set_ids.push(sid.clone());
            set_queues
                .entry(t.video_id.as_str())
                .or_default()
                .push_back(sid.clone());
        }
    }

    let mut target_set_ids = Vec::new();
    for t in &snap.playlist.tracks {
        if let Some(sid) = set_queues
            .get_mut(t.video_id.as_str())
            .and_then(VecDeque::pop_front)
        {
            target_set_ids.push(sid);
        }
    }

    if current_set_ids.len() == target_set_ids.len() && !target_set_ids.is_empty() {
        let (_, moves) = compute_minimal_moves(&current_set_ids, &target_set_ids);
        if !moves.is_empty() {
            ctx.client.move_playlist_items(&live.id, &moves).await?;
        }
    }

    writeln!(
        ctx.out,
        "Snapshot restore complete for '{}'.",
        snap.playlist.title
    )?;
    Ok(())
}
