const GENRE_FP_SALT: &str = "genre_split_plan_fp";

pub fn show_genre_split(
    ui: &mut egui::Ui,
    selected_playlist_id: Option<&str>,
    form: &mut GenreSplitForm,
    plan_state: &mut AsyncState<(Playlist, GenreSplitPlan)>,
    sync_queue: &mut SyncQueue,
    toast: &mut Option<ToastState>,
    cmd_tx: &Sender<WorkerCmd>,
) {
    ui.horizontal(|ui| {
        ui.label("Min tracks/genre:");
        ui.add(egui::DragValue::new(&mut form.min_tracks).range(1..=100));
        ui.label("Custom genres.toml (optional):");
        ui.text_edit_singleline(&mut form.custom_genres_toml);
    });

    let form_sig = hash_form(&(form.min_tracks, &form.custom_genres_toml));
    let current_fp =
        selected_playlist_id.map(|pid| make_fingerprint(pid, sync_queue.revision(), form_sig));
    let plan_is_fresh =
        current_fp.is_some() && load_plan_fingerprint(ui.ctx(), GENRE_FP_SALT) == current_fp;

    ui.horizontal_wrapped(|ui| {
        let can_plan = selected_playlist_id.is_some() && !plan_state.is_loading();
        if ui
            .add_enabled(
                can_plan,
                egui::Button::new("Enrich & Preview Split (Dry-Run)"),
            )
            .clicked()
            && let Some(pid) = selected_playlist_id
        {
            if let Some(fp) = &current_fp {
                store_plan_fingerprint(ui.ctx(), GENRE_FP_SALT, fp.clone());
            }
            *plan_state =
                AsyncState::Loading("Enriching genres (SQLite + MusicBrainz)...".to_string());
            let custom = (!form.custom_genres_toml.trim().is_empty())
                .then(|| PathBuf::from(form.custom_genres_toml.trim()));
            let _ = cmd_tx.send(WorkerCmd::PlanGenreSplit {
                playlist_id: pid.to_string(),
                min_tracks: form.min_tracks,
                custom_genres_path: custom,
            });
        }

        if let Some((_, plan)) = plan_state.data()
            && plan.buckets.iter().any(|b| !b.tracks_to_add.is_empty())
        {
            if ui
                .add_enabled(
                    plan_is_fresh,
                    egui::Button::new("Stage Genre Playlists to Sync"),
                )
                .clicked()
            {
                let mut staged = 0usize;
                let mut last_id = None;
                for bucket in &plan.buckets {
                    if bucket.tracks_to_add.is_empty() {
                        continue;
                    }
                    let eid = if let Some(existing_id) = &bucket.existing_playlist_id {
                        sync_queue.push(StagedOp::AddTracks {
                            playlist_id: existing_id.clone(),
                            playlist_title: bucket.target_playlist_title.clone(),
                            tracks: bucket.tracks_to_add.clone(),
                            allow_duplicates: false,
                        })
                    } else {
                        sync_queue.push(StagedOp::CreatePlaylist {
                            title: bucket.target_playlist_title.clone(),
                            description: "Generated by ytm-gui split-genre".to_string(),
                            privacy: PlaylistPrivacy::Private,
                            tracks: bucket.tracks_to_add.clone(),
                        })
                    };
                    last_id = Some(eid);
                    staged += 1;
                }
                *toast = Some(ToastState::staged(
                    format!("Staged {staged} genre bucket(s) in Sync."),
                    last_id,
                ));
            }
            if !plan_is_fresh {
                ui.colored_label(
                    egui::Color32::from_rgb(235, 180, 70),
                    "Parameters or playlist changed — re-run preview to stage.",
                );
            }
        }
    });

    let (loading, error) = match plan_state {
        AsyncState::Loading(m) => (Some(m.as_str()), None),
        AsyncState::Failed(e) => (None, Some(e.as_str())),
        _ => (None, None),
    };
    async_banner(ui, loading, error);
    ui.separator();

    let Some((_, plan)) = plan_state.data() else {
        ui.label("Click Enrich & Preview Split to partition the selected playlist by genre.");
        return;
    };

    ui.label(format!(
        "Buckets: {} | Skipped (< {} tracks): {}",
        plan.buckets.len(),
        form.min_tracks,
        plan.skipped_small_buckets
    ));

    TableBuilder::new(ui)
        .striped(true)
        .column(Column::initial(110.0))
        .column(Column::initial(200.0).clip(true))
        .column(Column::exact(70.0))
        .column(Column::exact(65.0))
        .column(Column::remainder())
        .header(22.0, |mut h| {
            for name in ["Genre", "Target Playlist", "Action", "To Add", "Existing"] {
                h.col(|ui| {
                    ui.strong(name);
                });
            }
        })
        .body(|body| {
            body.rows(20.0, plan.buckets.len(), |mut row| {
                let b = &plan.buckets[row.index()];
                let action = if b.existing_playlist_id.is_some() {
                    "APPEND"
                } else {
                    "CREATE"
                };
                row.col(|ui| {
                    ui.label(&b.genre);
                });
                row.col(|ui| {
                    ui.label(&b.target_playlist_title);
                });
                row.col(|ui| {
                    ui.label(action);
                });
                row.col(|ui| {
                    ui.label(b.tracks_to_add.len().to_string());
                });
                row.col(|ui| {
                    ui.label(b.already_present_count.to_string());
                });
            });
        });
}

pub fn show_snapshots(
    ui: &mut egui::Ui,
    snapshots_state: &AsyncState<Vec<SnapshotMetadata>>,
    detail_state: &mut AsyncState<Snapshot>,
    playlist_cache: &HashMap<String, Playlist>,
    sync_queue: &mut SyncQueue,
    toast: &mut Option<ToastState>,
    cmd_tx: &Sender<WorkerCmd>,
) {
    ui.horizontal(|ui| {
        if ui.button("Refresh Snapshots").clicked() {
            let _ = cmd_tx.send(WorkerCmd::RefreshSnapshots);
        }
        if let Some(snap) = detail_state.data()
            && ui.button("Stage Restore to Sync").clicked()
        {
            let eid = sync_queue.push(StagedOp::RestoreSnapshot {
                snapshot_id: snap.metadata.id.clone(),
                playlist_id: snap.playlist.id.clone(),
                playlist_title: snap.playlist.title.clone(),
            });
            *toast = Some(ToastState::staged(
                format!(
                    "Staged restore of '{}' onto '{}' in Sync.",
                    snap.metadata.id, snap.playlist.title
                ),
                Some(eid),
            ));
        }
    });
    ui.separator();

    let Some(snaps) = snapshots_state.data() else {
        ui.label("Loading local snapshots...");
        return;
    };

    let list_h = if detail_state.data().is_some() {
        (ui.available_height() * 0.45).max(120.0)
    } else {
        ui.available_height().max(160.0)
    };
    ui.allocate_ui(egui::vec2(ui.available_width(), list_h), |ui| {
        TableBuilder::new(ui)
            .id_salt("snapshots_tbl")
            .striped(true)
            .column(Column::initial(180.0).clip(true))
            .column(Column::initial(150.0).clip(true))
            .column(Column::initial(110.0))
            .column(Column::exact(50.0))
            .column(Column::remainder())
            .header(20.0, |mut h| {
                for name in ["Snapshot ID", "Playlist", "Reason", "Items", "Inspect"] {
                    h.col(|ui| {
                        ui.strong(name);
                    });
                }
            })
            .body(|body| {
                body.rows(22.0, snaps.len(), |mut row| {
                    let s = &snaps[row.index()];
                    let mut open_snap = false;
                    row.col(|ui| {
                        if ui
                            .add(egui::Label::new(&s.id).sense(egui::Sense::click()))
                            .on_hover_text("Double-click to inspect snapshot diff")
                            .double_clicked()
                        {
                            open_snap = true;
                        }
                    });
                    row.col(|ui| {
                        ui.label(&s.playlist_title);
                    });
                    row.col(|ui| {
                        ui.label(&s.reason);
                    });
                    row.col(|ui| {
                        ui.label(s.item_count.to_string());
                    });
                    row.col(|ui| {
                        if ui.button("Inspect").clicked() {
                            open_snap = true;
                        }
                    });
                    if open_snap {
                        *detail_state = AsyncState::Loading("Loading snapshot...".to_string());
                        let _ = cmd_tx.send(WorkerCmd::LoadSnapshot(s.id.clone()));
                    }
                });
            });
    });

    if let Some(snap) = detail_state.data() {
        ui.separator();
        ui.strong(format!(
            "Snapshot Diff Preview: {} | {} ({} tracks)",
            snap.metadata.id,
            snap.playlist.title,
            snap.playlist.tracks.len()
        ));
        if let Some(live) = playlist_cache.get(&snap.playlist.id) {
            let diff = plan_restore_diff(live, &snap.playlist);
            ui.horizontal(|ui| {
                ui.colored_label(
                    egui::Color32::from_rgb(90, 200, 120),
                    format!("+Add: {}", diff.added_tracks.len()),
                );
                ui.colored_label(
                    egui::Color32::from_rgb(235, 100, 100),
                    format!("-Remove: {}", diff.removed_tracks.len()),
                );
                ui.label(format!(
                    "⇄ Target Order: {} tracks",
                    diff.target_video_order.len()
                ));
            });
            egui::ScrollArea::vertical()
                .id_salt("snap_diff_scroll")
                .show(ui, |ui| {
                    for t in &diff.added_tracks {
                        ui.colored_label(
                            egui::Color32::from_rgb(90, 200, 120),
                            format!("+ {} — {}", t.title, t.primary_artist_name().unwrap_or("-")),
                        );
                    }
                    for t in &diff.removed_tracks {
                        ui.colored_label(
                            egui::Color32::from_rgb(235, 100, 100),
                            format!("- {} — {}", t.title, t.primary_artist_name().unwrap_or("-")),
                        );
                    }
                    if diff.added_tracks.is_empty() && diff.removed_tracks.is_empty() {
                        ui.weak("Same track set as cached playlist (order-only restore if positions differ).");
                    }
                });
        } else {
            ui.weak("Load this playlist in Inspector to preview live vs snapshot diff.");
        }
    }
}
